'use strict';
const assert=require('node:assert/strict');
module.exports=async h=>{
 const s=h.state,results=[];
 const closing=await h.read('/orders/'+s.orderId+'/closing');
 const jobs=(await h.read('/orders/'+s.orderId+'/work-orders')).workOrders;
 assert.equal(closing.status,'closed');assert.equal(closing.netDelivered,10);
 assert.equal(jobs.length,12);assert(jobs.every(j=>j.status==='complete'));
 results.push({test:'Order closed with 10 net delivered and all 12 work orders complete',status:'PASS'});
 await h.admin.goto('https://flow.getritim.com/?mode=api&view=shipping&order='+s.orderId+'&record='+s.steps.shipment.id);
 await h.admin.waitForFunction(()=>typeof RitimPremiumAPI!=='undefined'&&document.getElementById('app')?.getAttribute('aria-busy')!=='true',null,{timeout:90000});
 await h.admin.screenshot({path:require('node:path').join(h.out,'14-delivery-details-desktop.png'),fullPage:true});
 await h.admin.setViewportSize({width:390,height:844});
 await h.admin.screenshot({path:require('node:path').join(h.out,'14-delivery-details-mobile.png'),fullPage:true});
 await h.admin.setViewportSize({width:1440,height:1000});
 await h.role('operator');
 const key=Object.keys(s.steps).find(k=>k.startsWith('result-')),original=s.steps[key];
 assert(original);
 const base='/orders/'+s.orderId+'/work-orders/'+original.workOrderId+'/production';
 const body={lotId:original.lotId,kind:'pending',quantity:original.quantity,separateQualityRequest:true};
 const before=await h.read(base+'/balances',h.worker);
 assert(Number.isSafeInteger(before.consumedQuantity));
 const replay=await h.req(h.worker,base+'/results',body,s.prefix+'-'+key);
 assert.equal(replay.status,201);assert.equal(replay.data.eventId,original.eventId);
 const after=await h.read(base+'/balances',h.worker);
 assert.equal(after.consumedQuantity,before.consumedQuantity);
 const conflict=await h.req(h.worker,base+'/results',{...body,quantity:original.quantity+1},s.prefix+'-'+key);
 assert.equal(conflict.status,409);assert.equal(conflict.data.error.code,'IDEMPOTENCY_CONFLICT');
 results.push({test:'Same production request returns original event; altered payload rejected',status:'PASS',eventId:original.eventId});
 await h.role('quality');
 assert.equal((await h.req(h.worker,'/quality/queue')).status,200);
 const workspace=await h.read('/administration');
 const change=await h.req(h.admin,'/administration/member',{version:workspace.version,userId:h.operatorId,siteId:h.siteId,role:'viewer'});
 assert.equal(change.status,200);
 // Keep the existing quality browser session to verify server-side revocation.
 const denied=await h.req(h.worker,'/quality/queue');
 assert.equal(denied.status,403);
 results.push({test:'Existing quality session loses quality access immediately after downgrade',status:'PASS',httpStatus:denied.status});
 await h.role('operator');
 const session=await h.read('/api/v1/session',h.worker);
 assert(session.memberships.some(m=>m.roles.length===1&&m.roles[0]==='operator'));
 s.finalChecks=results;h.save();return results;
};
